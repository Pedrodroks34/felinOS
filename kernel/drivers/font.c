void font_init(void) {
    memset(&system_font, 0, sizeof(system_font));
    for (int i = 0; i < 256; i++) {
        for (int j = 0; j < 16; j++) {
            system_font.glyphs[i].data[j] = font_8x16_data[i][j];
        }
    }
    system_font.loaded = 1;
    klog("font: 8x16 system font loaded");
}

void font_render_char(int x, int y, char c, uint32_t fg_color, uint32_t bg_color) {
    if (!system_font.loaded) return;

    struct font_glyph *glyph = &system_font.glyphs[(unsigned char)c];
    uint8_t *fb = fb_buffer();
    uint32_t pitch = fb_width();
    uint32_t width = fb_width();
    uint32_t height = fb_height();

    for (int row = 0; row < FONT_HEIGHT; row++) {
        uint8_t bits = glyph->data[row];
        for (int col = 0; col < FONT_WIDTH; col++) {
            int px = x + col;
            int py = y + row;
            if (px >= 0 && px < (int)width && py >= 0 && py < (int)height) {
                if (bits & (0x80 >> col)) {
                    fb[py * pitch + px] = (uint8_t)fg_color;
                } else if (bg_color != 0xFFFFFFFF) {
                    fb[py * pitch + px] = (uint8_t)bg_color;
                }
            }
        }
    }
}

void font_render_string(int x, int y, const char *str, uint32_t fg_color, uint32_t bg_color) {
    int orig_x = x;
    while (*str) {
        if (*str == '\n') {
            x = orig_x;
            y += FONT_HEIGHT;
        } else if (*str == '\t') {
            x += FONT_WIDTH * 4;
        } else {
            font_render_char(x, y, *str, fg_color, bg_color);
            x += FONT_WIDTH;
        }
        str++;
    }
}

int font_text_width(const char *str) {
    return strlen(str) * FONT_WIDTH;
}

int font_text_height(void) {
    return FONT_HEIGHT;
}